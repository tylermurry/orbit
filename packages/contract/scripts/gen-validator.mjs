#!/usr/bin/env node
// Precompiles schema/orbit.schema.json into a standalone ESM validator (src/generated/schemaValidator.js).
// Why: Ajv normally compiles schemas at runtime with `new Function`, which a strict Content-Security-Policy
// (no 'unsafe-eval', as in the Orbit desktop app) blocks. The generated module needs no eval.
// Usage: node scripts/gen-validator.mjs [--check]   (--check exits 1 if the committed file is stale)
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { _ } from 'ajv/dist/compile/codegen/index.js';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const schema = JSON.parse(readFileSync(join(here, '../schema/orbit.schema.json'), 'utf8'));
const ajv = new Ajv2020({ allErrors: true, strict: true, allowUnionTypes: true, code: { source: true, esm: true, formats: _`__orbitFormats` } });
addFormats(ajv);
let code = standaloneCode(ajv, ajv.compile(schema));
// Make the module self-contained (no CommonJS require, no runtime deps): inline ucs2length and the formats used.
code = code.replace(/require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g, '__ucs2length');
if (/require\(/.test(code)) throw new Error('generated validator still contains require(): ' + code.match(/require\([^)]*\)/)[0]);
const usedFormats = [...new Set([...JSON.stringify(schema).matchAll(/"format":"([^"]+)"/g)].map((m) => m[1]))];
const supported = ['date-time'];
for (const f of usedFormats) if (!supported.includes(f)) throw new Error(`format '${f}' needs an inline implementation in gen-validator.mjs`);
const prelude = `
function __ucs2length(str) {
  let length = 0, pos = 0, value;
  while (pos < str.length) { length++; value = str.charCodeAt(pos++); if (value >= 0xd800 && value <= 0xdbff && pos < str.length) { value = str.charCodeAt(pos); if ((value & 0xfc00) === 0xdc00) pos++; } }
  return length;
}
// RFC 3339 date-time (same acceptance as ajv-formats "full" mode): calendar-valid date, time with seconds, offset required.
const __DT = /^(\\d{4})-(\\d{2})-(\\d{2})[Tt ](\\d{2}):(\\d{2}):(\\d{2})(\\.\\d+)?([Zz]|[+-](\\d{2}):(\\d{2}))$/;
function __dateTime(s) {
  const m = __DT.exec(s); if (!m) return false;
  const y = +m[1], mo = +m[2], d = +m[3], h = +m[4], mi = +m[5], se = +m[6];
  const leap = (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0;
  const dim = [31, leap ? 29 : 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31][mo - 1];
  if (!dim || d < 1 || d > dim) return false;
  if (h > 23 || mi > 59 || se > 60) return false;
  if (m[9] !== undefined && (+m[9] > 23 || +m[10] > 59)) return false;
  return true;
}
const __orbitFormats = { 'date-time': { validate: __dateTime } };
`;
code = code.replace('"use strict";', '"use strict";' + prelude);
const out = join(here, '../src/generated/schemaValidator.js');
const content = `/* eslint-disable */\n// @ts-nocheck\n// GENERATED by packages/contract/scripts/gen-validator.mjs from schema/orbit.schema.json — do not edit.\n${code}\n`;
if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== content) {
    console.error('src/generated/schemaValidator.js is stale. Run: npm run gen -w @orbit/contract');
    process.exit(1);
  }
  console.log('schemaValidator.js is up to date');
} else {
  writeFileSync(out, content);
  console.log(`wrote ${out}`);
}
